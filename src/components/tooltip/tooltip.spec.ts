      expect(tooltip.placement).to.equal('bottom');
      expect(tooltip.anchor).to.be.undefined;
      expect(tooltip.showTriggers).to.equal('pointerenter,focusin');
      expect(tooltip.hideTriggers).to.equal('pointerleave,click,focusout');
